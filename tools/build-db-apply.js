// Regenerates db/schema/apply.sql from what is actually on disk.
//
// apply.sql lists every file explicitly because psql has no glob. Maintaining
// 120-odd \i lines by hand would drift the first time someone adds a table,
// and the failure would be silent -- the new file simply never runs.
//
//   node tools/build-db-apply.js            rewrite it
//   node tools/build-db-apply.js --check    fail if it is out of date
const fs = require('fs');
const path = require('path');

const SCHEMA = path.join(__dirname, '..', 'db', 'schema');
const OUT = path.join(SCHEMA, 'apply.sql');
const CHECK = process.argv.includes('--check');

const list = (dir) =>
  fs.readdirSync(path.join(SCHEMA, dir)).filter((f) => f.endsWith('.sql')).sort();

const lines = [
  '-- ---------------------------------------------------------------------',
  '-- Rebuilds the whole schema, in dependency order.',
  '--',
  '--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f db/schema/apply.sql',
  '--',
  '-- Run from the repository root: the \\i paths are relative to it.',
  '--',
  '-- GENERATED by tools/build-db-apply.js -- do not edit by hand.',
  '-- Every file it includes is idempotent, so this is safe to re-run.',
  '-- ---------------------------------------------------------------------',
  '',
  '\\set ON_ERROR_STOP on',
  'begin;',
  '',
  '-- LANGUAGE sql function bodies are validated at CREATE time, and these',
  '-- functions call one another in no particular order. Deferring the check',
  '-- is what pg_restore does, for the same reason.',
  'set local check_function_bodies = off;',
  '',
  '\\echo == 00 prerequisites: extensions and enum types ==',
  '\\i db/schema/00_prerequisites.sql',
  '',
  '\\echo == 10 tables: structure, constraints, indexes, RLS enabled ==',
];
for (const f of list('10_tables')) lines.push('\\i db/schema/10_tables/' + f);

lines.push('', '\\echo == 20 functions ==');
for (const f of list('20_functions')) lines.push('\\i db/schema/20_functions/' + f);

lines.push('', '\\echo == 30 policies, triggers, function-dependent constraints ==');
for (const f of list('30_policies')) lines.push('\\i db/schema/30_policies/' + f);

lines.push('', '\\echo == 40 grants ==', '\\i db/schema/40_grants.sql');
lines.push('', '\\echo == 50 storage buckets ==', '\\i db/schema/50_storage.sql');
lines.push('', '\\echo == 60 per-tooth work order cutover ==', '\\i db/schema/60_per_tooth_work_order_cutover.sql');
lines.push('', 'commit;', '');

const content = lines.join('\n');
const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;

if (CHECK) {
  if (current !== content) {
    console.error('db/schema/apply.sql is out of date. Run: node tools/build-db-apply.js');
    process.exit(1);
  }
  console.log('apply.sql is up to date (' + lines.filter((l) => l.startsWith('\\i')).length + ' includes)');
} else {
  fs.writeFileSync(OUT, content);
  console.log('wrote apply.sql (' + lines.filter((l) => l.startsWith('\\i')).length + ' includes)');
}
