-- A pending or refused submission cannot enter production or be locked.
CREATE OR REPLACE FUNCTION public.guard_external_order_production()
RETURNS trigger LANGUAGE plpgsql SET search_path=public AS $$
BEGIN
 IF NEW.order_origin IN ('doctor','lab_partner') AND NEW.approval_state<>'approved' AND
   (NEW.locked OR NEW.status<>'Not Started' OR
    coalesce(NEW.status_model,'Not Started')<>'Not Started' OR
    coalesce(NEW.status_modelare,'Not Started')<>'Not Started' OR
    coalesce(NEW.status_cer_fin,'Not Started')<>'Not Started' OR
    NEW.tehnician_model IS NOT NULL OR NEW.tehnician1_modelare IS NOT NULL OR
    NEW.tehnician2_cer_fin IS NOT NULL OR NEW.archived_at IS NOT NULL) THEN
   RAISE EXCEPTION 'Order must be approved before production';
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS guard_external_order_production ON public.lab_work_orders;
CREATE TRIGGER guard_external_order_production BEFORE INSERT OR UPDATE ON public.lab_work_orders
FOR EACH ROW EXECUTE FUNCTION public.guard_external_order_production();

-- Existing Doctor RPCs still insert through lab_work_orders. Stamp their origin
-- before the production guard, including clients using the legacy date RPC.
CREATE OR REPLACE FUNCTION public.stamp_external_order_origin()
RETURNS trigger LANGUAGE plpgsql SET search_path=public AS $$
BEGIN
 IF public.effective_lab_role(NEW.lab_organization_id)='doctor' AND NEW.order_origin='internal' THEN
   NEW.order_origin:='doctor'; NEW.approval_state:='pending';
   SELECT id INTO NEW.partner_id FROM public.lab_partners
   WHERE lab_organization_id=NEW.lab_organization_id AND active
     AND lower(trim(name))=lower(trim(NEW.nume_partener)) LIMIT 1;
   IF NEW.partner_id IS NULL THEN RAISE EXCEPTION 'Doctor partner is not in the active catalog'; END IF;
 END IF;
 IF NEW.deadline_at IS NULL AND NEW.deadline IS NOT NULL THEN
   NEW.deadline_at:=(NEW.deadline::timestamp+interval '23 hours 59 minutes') AT TIME ZONE 'Europe/Bucharest';
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS stamp_external_order_origin ON public.lab_work_orders;
CREATE TRIGGER stamp_external_order_origin BEFORE INSERT ON public.lab_work_orders
FOR EACH ROW EXECUTE FUNCTION public.stamp_external_order_origin();
UPDATE public.lab_work_orders SET deadline_at=(deadline::timestamp+interval '23 hours 59 minutes') AT TIME ZONE 'Europe/Bucharest'
WHERE deadline_at IS NULL AND deadline IS NOT NULL;

CREATE OR REPLACE FUNCTION public.review_external_work_order
(p_lab uuid,p_order bigint,p_decision text,p_reason text DEFAULT NULL)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_state text:=lower(trim(p_decision)); v_reason text:=nullif(trim(coalesce(p_reason,'')),'');
BEGIN
 IF NOT public.is_lab_management(p_lab) THEN RAISE EXCEPTION 'Management access denied'; END IF;
 IF v_state NOT IN ('approve','reject') OR length(coalesce(v_reason,''))>1000 THEN
   RAISE EXCEPTION 'Invalid review decision or reason';
 END IF;
 UPDATE public.lab_work_orders SET
   approval_state=CASE WHEN v_state='approve' THEN 'approved' ELSE 'rejected' END,
   approval_reviewed_at=now(),approval_reviewed_by_user_id=auth.uid(),approval_reason=v_reason,
   updated_at=now()
 WHERE lab_organization_id=p_lab AND id=p_order AND order_origin IN ('doctor','lab_partner')
   AND approval_state='pending';
 IF NOT FOUND THEN RAISE EXCEPTION 'Order is not awaiting approval'; END IF;
 INSERT INTO public.lab_work_order_approval_events
 (lab_organization_id,work_order_id,state,reason,actor_user_id)
 VALUES(p_lab,p_order,CASE WHEN v_state='approve' THEN 'approved' ELSE 'rejected' END,v_reason,auth.uid());
 RETURN true;
END $$;
REVOKE ALL ON FUNCTION public.review_external_work_order(uuid,bigint,text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.review_external_work_order(uuid,bigint,text,text) TO authenticated;

