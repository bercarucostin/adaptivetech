-- Include linked Lab Partner accounts among authorized approval recipients.
CREATE OR REPLACE FUNCTION public.email_notification_recipient_allowed(p_user uuid,p_lab uuid,p_order bigint,p_kind text,p_stage text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT EXISTS (
 SELECT 1 FROM public.profiles p JOIN public.lab_work_orders w ON w.lab_organization_id=p_lab AND w.id=p_order
 WHERE p.id=p_user AND p.active AND w.archived_at IS NULL
 AND p_kind IN ('new_work_order','work_order_status','assignment','approval_state')
 AND CASE WHEN p_kind='work_order_status' THEN p.notify_stage_status ELSE p.notify_new_work_order END
 AND (
  (p_kind<>'assignment' AND EXISTS(SELECT 1 FROM public.organization_memberships m WHERE m.organization_id=p_lab AND m.user_id=p.id AND m.status='active' AND lower(m.role) IN ('admin','manager')))
  OR (
   EXISTS(SELECT 1 FROM public.organization_memberships m WHERE m.organization_id=p_lab AND m.user_id=p.id AND m.status='active' AND lower(m.role)='technician')
   AND nullif(trim(p.technician_name),'') IS NOT NULL
   -- Ambiguous names must not route a private notification to multiple accounts.
   AND 1=(SELECT count(*) FROM public.profiles p2 JOIN public.organization_memberships m2 ON m2.user_id=p2.id AND m2.organization_id=p_lab AND m2.status='active' AND lower(m2.role)='technician' WHERE p2.active AND lower(trim(p2.technician_name))=lower(trim(p.technician_name)))
   AND EXISTS(SELECT 1 FROM (VALUES
    ('model',w.tehnician_model,w.model_not_applicable),('modelare',w.tehnician1_modelare,w.modelare_not_applicable),('cer_fin',w.tehnician2_cer_fin,w.cer_fin_not_applicable)
   ) s(stage,technician,not_applicable) WHERE NOT coalesce(s.not_applicable,false) AND (p_stage IS NULL OR s.stage=p_stage) AND lower(trim(s.technician))=lower(trim(p.technician_name)))
  )
  OR (p_kind<>'assignment' AND nullif(trim(w.nume_partener),'') IS NOT NULL
   AND lower(trim(w.nume_partener)) IN (lower(trim(p.legacy_partner_name)),lower(trim(p.display_name)),lower(trim(p.legacy_user_id)))
   AND EXISTS(SELECT 1 FROM public.organization_memberships m JOIN public.organizations clinic ON clinic.id=m.organization_id AND clinic.organization_type='clinic'
    JOIN public.organization_relationships r ON r.clinic_organization_id=m.organization_id AND r.lab_organization_id=p_lab AND r.status='active'
    WHERE m.user_id=p.id AND m.status='active' AND lower(m.role)='doctor')
  )
  OR (p_kind='approval_state' AND EXISTS(
   SELECT 1 FROM public.lab_partner_user_links link
   JOIN public.organization_memberships m ON m.organization_id=link.lab_organization_id
    AND m.user_id=link.user_id AND m.status='active' AND lower(m.role) IN ('lab partner','lab_partner')
   JOIN public.lab_partners partner ON partner.id=link.partner_id
    AND partner.lab_organization_id=link.lab_organization_id AND partner.active
   WHERE link.lab_organization_id=p_lab AND link.user_id=p.id AND link.partner_id=w.partner_id
  ))
 ));
$$;
REVOKE ALL ON FUNCTION public.email_notification_recipient_allowed(uuid,uuid,bigint,text,text) FROM PUBLIC,anon,authenticated,service_role;


-- Keep the legacy Doctor edit RPC behind the review lifecycle.
CREATE OR REPLACE FUNCTION public.update_doctor_work_order(p_lab_organization_id uuid, p_work_order_id bigint, p_deadline date, p_nume_pacient text, p_items jsonb, p_case jsonb DEFAULT '{}'::jsonb)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_order public.lab_work_orders%rowtype;
begin
    if not public.is_connected_doctor_for_lab(p_lab_organization_id) then
        raise exception 'Doctor access denied';
    end if;

    select *
      into v_order
    from public.lab_work_orders
    where lab_organization_id = p_lab_organization_id
      and id = p_work_order_id
    for update;

    if not found or not public.doctor_matches_partner(v_order.nume_partener) then
        raise exception 'Work Order access denied';
    end if;

    if v_order.order_origin='doctor' and v_order.approval_state<>'rejected' then
        raise exception 'Only rejected Doctor orders can be edited and resubmitted';
    end if;

    if v_order.locked then
        raise exception 'Work Order is locked';
    end if;

    if lower(trim(coalesce(v_order.status,''))) <> 'not started' then
        raise exception 'Doctor can edit only Not Started Work Orders';
    end if;

    if trim(coalesce(p_nume_pacient,'')) = '' then
        raise exception 'Nume_Pacient is required';
    end if;

    update public.lab_work_orders
    set
        deadline = p_deadline,
        nume_pacient = trim(p_nume_pacient),
        updated_by_user_id = public.current_legacy_user_id(),
        updated_at = now()
    where lab_organization_id = p_lab_organization_id
      and id = p_work_order_id;

    perform public.replace_work_order_items(p_lab_organization_id,p_work_order_id,p_items,'General');
    perform public.save_work_order_clinical_case(p_lab_organization_id,p_work_order_id,p_case);
    return true;
end;
$function$
;

-- Show frozen urgency and review metadata on the clinical price sheet.
CREATE OR REPLACE FUNCTION public.get_work_order_price_lines(p_lab uuid,p_order bigint)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path=public
AS $$
DECLARE
    v_role text := public.effective_lab_role(p_lab);
    v_result jsonb;
BEGIN
    IF coalesce(v_role,'') NOT IN ('admin','manager','doctor') THEN
        RAISE EXCEPTION 'Price line access denied';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.lab_work_orders wo
        WHERE wo.lab_organization_id=p_lab AND wo.id=p_order
    ) THEN RAISE EXCEPTION 'Work Order not found'; END IF;
    IF v_role='doctor' AND NOT public.can_access_work_order(p_lab,p_order) THEN
        RAISE EXCEPTION 'Price line access denied';
    END IF;

    SELECT jsonb_build_object(
        'lines',coalesce((
            SELECT jsonb_agg(jsonb_build_object(
                'work_type',line.work_type,'billing_mode',line.billing_mode,
                'billing_scope',line.billing_scope,'quantity',line.quantity,
                'contract',line.contract,'unit_price',line.unit_price,
                'subtotal',line.line_total,'base_subtotal',line.base_line_total,
                'urgent_percent',line.urgent_percent,'urgency_surcharge',line.urgency_surcharge,
                'matched',line.unit_price IS NOT NULL,
                'price_source',line.price_source,'price_fixed_at',line.price_fixed_at,
                'price_migrated',line.price_migrated
            ) ORDER BY line.work_type,line.billing_scope)
            FROM public.lab_work_order_price_lines line
            WHERE line.lab_organization_id=p_lab AND line.work_order_id=p_order
        ),'[]'::jsonb),
        'element_count',coalesce((
            SELECT count(*) FROM public.lab_work_order_items item
            WHERE item.lab_organization_id=p_lab AND item.work_order_id=p_order
        ),0),
        'billing_unit_count',coalesce((
            SELECT sum(line.quantity) FROM public.lab_work_order_price_lines line
            WHERE line.lab_organization_id=p_lab AND line.work_order_id=p_order
        ),0),
        'list_price',wo.snapshot_list_price,'discount',wo.discount,
        'final_price',wo.snapshot_final_price,'partner_name',wo.nume_partener,
        'deadline_at',wo.deadline_at,'approval_state',wo.approval_state,
        'approval_reason',wo.approval_reason
    ) INTO v_result
    FROM public.lab_work_orders wo
    WHERE wo.lab_organization_id=p_lab AND wo.id=p_order;
    RETURN v_result;
END;
$$;

REVOKE ALL ON FUNCTION public.get_work_order_price_lines(uuid,bigint) FROM public,anon;
GRANT EXECUTE ON FUNCTION public.get_work_order_price_lines(uuid,bigint) TO authenticated;
