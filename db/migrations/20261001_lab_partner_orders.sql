CREATE OR REPLACE FUNCTION public.save_lab_partner_lines(p_lab uuid,p_order bigint,p_quote jsonb,p_note text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_line jsonb;
BEGIN
 IF NOT public.lab_partner_can_access_order(p_lab,p_order) THEN RAISE EXCEPTION 'Order access denied'; END IF;
 DELETE FROM public.lab_partner_work_order_items WHERE lab_organization_id=p_lab AND work_order_id=p_order;
 FOR v_line IN SELECT value FROM jsonb_array_elements(p_quote->'lines') LOOP
   INSERT INTO public.lab_partner_work_order_items
   (lab_organization_id,work_order_id,line_no,work_type,color,quantity,processing_requested,note)
   VALUES(p_lab,p_order,(v_line->>'line_no')::integer,v_line->>'work_type',v_line->>'color',
     (v_line->>'quantity')::integer,(v_line->>'processing_requested')::boolean,
     CASE WHEN (v_line->>'line_no')::integer=1 THEN nullif(left(trim(coalesce(p_note,'')),2000),'') END);
   INSERT INTO public.lab_partner_work_order_price_lines
   (lab_organization_id,work_order_id,line_no,contract,base_unit_price,base_subtotal,
    processing_unit_amount,urgent_percent,urgency_surcharge,line_total)
   VALUES(p_lab,p_order,(v_line->>'line_no')::integer,v_line->>'contract',
    (v_line->>'base_unit_price')::numeric,(v_line->>'base_subtotal')::numeric,
    (v_line->>'processing_unit_amount')::numeric,(v_line->>'urgent_percent')::numeric,
    (v_line->>'urgency_surcharge')::numeric,(v_line->>'line_total')::numeric);
 END LOOP;
END $$;
REVOKE ALL ON FUNCTION public.save_lab_partner_lines(uuid,bigint,jsonb,text) FROM PUBLIC,authenticated;

