CREATE OR REPLACE FUNCTION public.lab_partner_quote(p_lab uuid,p_items jsonb,p_deadline_at timestamptz)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=public AS $$
DECLARE
 v_partner uuid; v_name text; v_default text; v_hours integer;
 v_urgent boolean; v_item jsonb; v_type public.lab_work_types%rowtype;
 v_price public.lab_contract_work_prices%rowtype;
 v_percent numeric; v_processing numeric; v_base numeric; v_amount numeric;
 v_surcharge numeric; v_total numeric:=0; v_lines jsonb:='[]'::jsonb;
 v_qty integer; v_selected boolean; v_index integer:=0;
BEGIN
 SELECT partner_id,partner_name INTO v_partner,v_name FROM public.lab_partner_identity(p_lab);
 IF v_partner IS NULL THEN RAISE EXCEPTION 'Lab Partner mapping is missing'; END IF;
 IF p_deadline_at IS NULL OR p_deadline_at <= now() THEN RAISE EXCEPTION 'Deadline must be in the future'; END IF;
 IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) NOT BETWEEN 1 AND 100 THEN
   RAISE EXCEPTION 'Provide 1 to 100 commercial lines';
 END IF;
 SELECT default_contract,urgent_window_hours INTO v_default,v_hours
 FROM public.lab_order_pricing_settings WHERE lab_organization_id=p_lab;
 v_default:=coalesce(nullif(trim(v_default),''),'General');
 v_hours:=coalesce(v_hours,24);
 v_urgent:=(p_deadline_at-now()) < make_interval(hours=>v_hours);
 FOR v_item IN SELECT value FROM jsonb_array_elements(p_items) LOOP
   v_index:=v_index+1;
   IF jsonb_typeof(v_item) <> 'object' OR coalesce(v_item->>'quantity','') !~ '^[1-9][0-9]{0,4}$'
      OR jsonb_typeof(v_item->'processing_requested') NOT IN ('boolean','null')
      OR length(coalesce(v_item->>'color',''))>120 THEN
      RAISE EXCEPTION 'Invalid commercial line %',v_index;
   END IF;
   v_qty:=(v_item->>'quantity')::integer;
   v_selected:=coalesce((v_item->>'processing_requested')::boolean,false);
   SELECT * INTO v_type FROM public.lab_work_types wt
   WHERE wt.lab_organization_id=p_lab AND wt.active
     AND lower(trim(wt.tip_lucrare))=lower(trim(v_item->>'work_type'))
   ORDER BY wt.id LIMIT 1;
   IF NOT FOUND THEN RAISE EXCEPTION 'Invalid active work type on line %',v_index; END IF;
   IF v_selected AND NOT v_type.processing_enabled THEN
     RAISE EXCEPTION 'Processing is not enabled for %',v_type.tip_lucrare;
   END IF;
   SELECT * INTO v_price FROM public.lab_contract_work_prices cp
   WHERE cp.lab_organization_id=p_lab AND lower(trim(cp.tip_lucrare))=lower(trim(v_type.tip_lucrare))
     AND lower(trim(cp.contract)) IN (lower(trim(v_name)),lower(trim(v_default)))
   ORDER BY CASE WHEN lower(trim(cp.contract))=lower(trim(v_name)) THEN 0 ELSE 1 END,cp.id LIMIT 1;
   IF NOT FOUND THEN RAISE EXCEPTION 'Missing contract price for %',v_type.tip_lucrare; END IF;
   SELECT coalesce(v_price.urgent_percent_override,d.urgent_percent,0),
          coalesce(v_price.processing_amount_override,d.processing_amount,0)
   INTO v_percent,v_processing FROM (SELECT 1) s
   LEFT JOIN public.lab_contract_pricing_defaults d
     ON d.lab_organization_id=p_lab AND lower(trim(d.contract))=lower(trim(v_price.contract));
   v_percent:=CASE WHEN v_urgent THEN v_percent ELSE 0 END;
   v_processing:=CASE WHEN v_selected THEN v_processing ELSE 0 END;
   v_base:=round(v_price.pret*v_qty,2);
   v_amount:=round(v_processing*v_qty,2);
   v_surcharge:=round((v_base+v_amount)*v_percent/100,2);
   v_total:=v_total+v_base+v_amount+v_surcharge;
   v_lines:=v_lines||jsonb_build_array(jsonb_build_object(
     'line_no',v_index,'work_type',v_type.tip_lucrare,'color',nullif(trim(coalesce(v_item->>'color','')),''),
     'quantity',v_qty,'processing_requested',v_selected,'contract',v_price.contract,
     'base_unit_price',v_price.pret,'base_subtotal',v_base,
     'processing_unit_amount',v_processing,'processing_subtotal',v_amount,
     'urgent_percent',v_percent,'urgency_surcharge',v_surcharge,
     'line_total',v_base+v_amount+v_surcharge));
 END LOOP;
 RETURN jsonb_build_object('partner_id',v_partner,'partner_name',v_name,
  'urgent',v_urgent,'urgent_window_hours',v_hours,'lines',v_lines,
  'final_price',round(v_total,2));
END $$;
REVOKE ALL ON FUNCTION public.lab_partner_quote(uuid,jsonb,timestamptz) FROM PUBLIC;

