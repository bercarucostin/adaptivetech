CREATE OR REPLACE FUNCTION public.apply_doctor_order_urgency(p_lab uuid,p_order bigint,p_deadline_at timestamptz)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_hours integer; v_urgent boolean; v_total numeric; v_line public.lab_work_order_price_lines%rowtype; v_percent numeric;
BEGIN
 IF public.effective_lab_role(p_lab)<>'doctor' OR NOT public.can_access_work_order(p_lab,p_order) THEN
   RAISE EXCEPTION 'Doctor access denied';
 END IF;
 IF p_deadline_at IS NULL OR p_deadline_at<=now() THEN RAISE EXCEPTION 'Deadline must be in the future'; END IF;
 SELECT urgent_window_hours INTO v_hours FROM public.lab_order_pricing_settings
 WHERE lab_organization_id=p_lab;
 v_urgent:=(p_deadline_at-now()) < make_interval(hours=>coalesce(v_hours,24));
 FOR v_line IN SELECT * FROM public.lab_work_order_price_lines
 WHERE lab_organization_id=p_lab AND work_order_id=p_order LOOP
   SELECT coalesce(cp.urgent_percent_override,d.urgent_percent,0) INTO v_percent
   FROM (SELECT 1) s
   LEFT JOIN public.lab_contract_pricing_defaults d ON d.lab_organization_id=p_lab
     AND lower(trim(d.contract))=lower(trim(v_line.contract))
   LEFT JOIN public.lab_contract_work_prices cp ON cp.lab_organization_id=p_lab
     AND lower(trim(cp.contract))=lower(trim(v_line.contract))
     AND lower(trim(cp.tip_lucrare))=lower(trim(v_line.work_type))
   ORDER BY cp.id LIMIT 1;
   v_percent:=CASE WHEN v_urgent THEN coalesce(v_percent,0) ELSE 0 END;
   UPDATE public.lab_work_order_price_lines SET
     base_line_total=coalesce(v_line.base_line_total,v_line.line_total),
     urgent_percent=v_percent,
     urgency_surcharge=coalesce(round(coalesce(v_line.base_line_total,v_line.line_total)*v_percent/100,2),0),
     line_total=CASE WHEN v_line.line_total IS NULL THEN NULL ELSE
       coalesce(v_line.base_line_total,v_line.line_total)+round(coalesce(v_line.base_line_total,v_line.line_total)*v_percent/100,2) END
   WHERE lab_organization_id=p_lab AND work_order_id=p_order
     AND work_type=v_line.work_type AND billing_scope=v_line.billing_scope;
 END LOOP;
 SELECT CASE WHEN count(*) FILTER (WHERE line_total IS NULL)>0 THEN NULL ELSE sum(line_total) END
 INTO v_total FROM public.lab_work_order_price_lines
 WHERE lab_organization_id=p_lab AND work_order_id=p_order;
 UPDATE public.lab_work_orders SET deadline=(p_deadline_at AT TIME ZONE 'Europe/Bucharest')::date,
 deadline_at=p_deadline_at,snapshot_list_price=v_total,snapshot_final_price=v_total,
 price_fixed_at=now() WHERE lab_organization_id=p_lab AND id=p_order;
END $$;
REVOKE ALL ON FUNCTION public.apply_doctor_order_urgency(uuid,bigint,timestamptz) FROM PUBLIC,authenticated;

