CREATE OR REPLACE FUNCTION public.estimate_doctor_work_order_v2
(p_lab uuid,p_deadline_at timestamptz,p_items jsonb)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=public AS $$
DECLARE v_est jsonb; v_lines jsonb:='[]'::jsonb; v_line jsonb;
 v_hours integer; v_urgent boolean; v_percent numeric; v_subtotal numeric; v_surcharge numeric; v_total numeric:=0;
BEGIN
 IF public.effective_lab_role(p_lab)<>'doctor' THEN RAISE EXCEPTION 'Doctor access denied'; END IF;
 IF p_deadline_at IS NULL OR p_deadline_at<=now() THEN RAISE EXCEPTION 'Deadline must be in the future'; END IF;
 v_est:=public.estimate_work_order_items(p_lab,NULL,'General',p_items,0);
 SELECT urgent_window_hours INTO v_hours FROM public.lab_order_pricing_settings WHERE lab_organization_id=p_lab;
 v_hours:=coalesce(v_hours,24);
 v_urgent:=(p_deadline_at-now())<make_interval(hours=>v_hours);
 FOR v_line IN SELECT value FROM jsonb_array_elements(v_est->'lines') LOOP
   SELECT coalesce(cp.urgent_percent_override,d.urgent_percent,0) INTO v_percent
   FROM (SELECT 1) s
   LEFT JOIN public.lab_contract_pricing_defaults d ON d.lab_organization_id=p_lab
    AND lower(trim(d.contract))=lower(trim(v_line->>'contract'))
   LEFT JOIN public.lab_contract_work_prices cp ON cp.lab_organization_id=p_lab
    AND lower(trim(cp.contract))=lower(trim(v_line->>'contract'))
    AND lower(trim(cp.tip_lucrare))=lower(trim(v_line->>'work_type'))
   ORDER BY cp.id LIMIT 1;
   v_percent:=CASE WHEN v_urgent THEN coalesce(v_percent,0) ELSE 0 END;
   v_subtotal:=(v_line->>'subtotal')::numeric;
   v_surcharge:=round(v_subtotal*v_percent/100,2);
   v_total:=v_total+v_subtotal+v_surcharge;
   v_lines:=v_lines||jsonb_build_array(v_line||jsonb_build_object(
    'base_subtotal',v_subtotal,'urgent_percent',v_percent,
    'urgency_surcharge',v_surcharge,'subtotal',v_subtotal+v_surcharge));
 END LOOP;
 RETURN v_est||jsonb_build_object('lines',v_lines,'list_price',round(v_total,2),
   'final_price',round(v_total,2),'urgent',v_urgent,'urgent_window_hours',v_hours);
END $$;
