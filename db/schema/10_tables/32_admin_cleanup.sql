ALTER TABLE public.admin_cleanup_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_cleanup_files ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lab_work_order_id_watermarks ENABLE ROW LEVEL SECURITY;
CREATE INDEX IF NOT EXISTS admin_cleanup_jobs_due_idx ON public.admin_cleanup_jobs(state,reconcile_after,created_at);
CREATE INDEX IF NOT EXISTS admin_cleanup_items_job_idx ON public.admin_cleanup_items(job_id,state,order_id);
CREATE INDEX IF NOT EXISTS admin_cleanup_items_order_idx ON public.admin_cleanup_items(order_id,state);

